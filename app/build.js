// Builds the static demo: dist/index.html, one self-contained file.
// Run with: npm run build:demo
const fs = require('node:fs');
const path = require('node:path');
const ejs = require('ejs');
const esbuild = require('esbuild');

const root = __dirname;
const viewsDir = path.join(root, 'views');
const buildDir = path.join(root, 'build');
const distDir = path.join(root, 'dist');
fs.mkdirSync(buildDir, { recursive: true });
fs.mkdirSync(distDir, { recursive: true });

// 1. Precompile every template to a plain function(locals, escapeFn, include).
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name)) : d.name.endsWith('.ejs') ? [path.join(dir, d.name)] : []);
}

function walkFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walkFiles(path.join(dir, d.name)) : [path.join(dir, d.name)]);
}

const entries = walk(viewsDir).map((file) => {
  const name = path.relative(viewsDir, file).replace(/\\/g, '/').replace(/\.ejs$/, '');
  const tpl = new ejs.Template(fs.readFileSync(file, 'utf8'), { client: true, compileDebug: false, filename: file });
  tpl.compile();
  return `  ${JSON.stringify(name)}: function (locals, escapeFn, include) {\n${tpl.source}\n  }`;
});
fs.writeFileSync(path.join(buildDir, 'templates.js'),
  `// Generated by build.js. Do not edit.\nmodule.exports = {\n${entries.join(',\n')}\n};\n`);

// 2. Embed the images in public/img as data: URLs, keyed by their path in public/.
const types = { '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml' };
const publicDir = path.join(root, 'public');
const imgDir = path.join(publicDir, 'img');
const images = fs.existsSync(imgDir) ? walkFiles(imgDir).filter((f) => types[path.extname(f)]) : [];
const assets = Object.fromEntries(images.map((f) => [
  path.relative(publicDir, f).replace(/\\/g, '/'),
  `data:${types[path.extname(f)]};base64,${fs.readFileSync(f).toString('base64')}`,
]));
fs.writeFileSync(path.join(buildDir, 'assets.js'),
  `// Generated by build.js. Do not edit.
module.exports = ${JSON.stringify(assets, null, 1)};
`);

// 3. Bundle the browser runtime with the shared core and mock data.
const js = esbuild.buildSync({
  entryPoints: [path.join(root, 'client', 'main.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2020'],
  write: false,
}).outputFiles[0].text;

// 4. Inline everything into one HTML file.
const css = ['reset.css', 'styles.css']
  .map((f) => fs.readFileSync(path.join(root, 'public', 'css', f), 'utf8'))
  .join('\n');

const html = `<!doctype html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="robots" content="noindex">
<title>Pill Sorter – demo</title>
<style>${css}</style>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script>
</head>
<body>
<noscript><p style="padding:1rem">This demo needs JavaScript turned on.</p></noscript>
</body>
</html>
`;
fs.writeFileSync(path.join(distDir, 'index.html'), html);
console.log(`Built dist/index.html (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB, ${entries.length} templates, ${images.length} images)`);
